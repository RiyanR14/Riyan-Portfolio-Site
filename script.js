function bindInteractiveGlow() {
  const glowTargets = document.querySelectorAll(
    ".highlight-card, .panel, .project-card, .cert-card, .timeline-item, .contact-card"
  );

  glowTargets.forEach((target) => {
    target.addEventListener("pointermove", (event) => {
      const rect = target.getBoundingClientRect();
      const x = event.clientX - rect.left;
      const y = event.clientY - rect.top;

      const glowX = (x / rect.width) * 100;
      const glowY = (y / rect.height) * 100;

      target.style.setProperty("--glow-x", `${glowX}%`);
      target.style.setProperty("--glow-y", `${glowY}%`);

      // 3D Card Tilt Effect
      const centerX = rect.width / 2;
      const centerY = rect.height / 2;
      const tiltX = ((centerY - y) / centerY) * 10; // max 10 degrees tilt
      const tiltY = ((x - centerX) / centerX) * 10;

      target.style.transform = `perspective(1000px) rotateX(${tiltX}deg) rotateY(${tiltY}deg) translateY(-4px)`;
      target.style.transition = "transform 0.1s ease";
    });

    target.addEventListener("pointerleave", () => {
      target.style.transform = "";
      target.style.transition = "transform 0.5s ease";
    });
  });
}

function startMotionField() {
  const canvas = document.querySelector("#motionField");
  if (!canvas || window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    return;
  }

  const context = canvas.getContext("2d");
  if (!context) {
    return;
  }

  const points = [];
  const pointCount = 54;
  let width = 0;
  let height = 0;
  let animationFrame = 0;

  // Track mouse position for physical interaction
  const mouse = { x: null, y: null, radius: 160 };

  window.addEventListener("pointermove", (event) => {
    mouse.x = event.clientX;
    mouse.y = event.clientY;
  });

  window.addEventListener("pointerleave", () => {
    mouse.x = null;
    mouse.y = null;
  });

  function resize() {
    const ratio = Math.min(window.devicePixelRatio || 1, 2);
    width = window.innerWidth;
    height = window.innerHeight;
    canvas.width = width * ratio;
    canvas.height = height * ratio;
    canvas.style.width = `${width}px`;
    canvas.style.height = `${height}px`;
    context.setTransform(ratio, 0, 0, ratio, 0, 0);

    points.length = 0;
    for (let index = 0; index < pointCount; index += 1) {
      points.push({
        x: Math.random() * width,
        y: Math.random() * height,
        vx: (Math.random() - 0.5) * 0.34,
        vy: (Math.random() - 0.5) * 0.34,
        size: 1.2 + Math.random() * 1.8
      });
    }
  }

  function draw() {
    context.clearRect(0, 0, width, height);

    const gradient = context.createLinearGradient(0, 0, width, height);
    gradient.addColorStop(0, "rgba(6, 182, 212, 0.11)");
    gradient.addColorStop(0.5, "rgba(16, 185, 129, 0.08)");
    gradient.addColorStop(1, "rgba(255, 255, 255, 0.02)");

    points.forEach((point, index) => {
      // Attract/Repel physical forces from mouse pointer
      if (mouse.x !== null && mouse.y !== null) {
        const dx = point.x - mouse.x;
        const dy = point.y - mouse.y;
        const dist = Math.hypot(dx, dy);
        if (dist < mouse.radius) {
          const force = (mouse.radius - dist) / mouse.radius; // 0 to 1
          const angle = Math.atan2(dy, dx);
          // Push away from mouse
          point.x += Math.cos(angle) * force * 1.8;
          point.y += Math.sin(angle) * force * 1.8;
        }
      }

      point.x += point.vx;
      point.y += point.vy;

      if (point.x < -20) point.x = width + 20;
      if (point.x > width + 20) point.x = -20;
      if (point.y < -20) point.y = height + 20;
      if (point.y > height + 20) point.y = -20;

      context.beginPath();
      context.arc(point.x, point.y, point.size, 0, Math.PI * 2);
      context.fillStyle = index % 3 === 0 ? "rgba(16, 185, 129, 0.2)" : "rgba(6, 182, 212, 0.2)";
      context.fill();

      for (let nextIndex = index + 1; nextIndex < points.length; nextIndex += 1) {
        const next = points[nextIndex];
        const distance = Math.hypot(point.x - next.x, point.y - next.y);

        if (distance < 145) {
          context.beginPath();
          context.moveTo(point.x, point.y);
          context.lineTo(next.x, next.y);
          context.strokeStyle = gradient;
          context.globalAlpha = (145 - distance) / 145;
          context.lineWidth = 1;
          context.stroke();
          context.globalAlpha = 1;
        }
      }
    });

    animationFrame = requestAnimationFrame(draw);
  }

  window.addEventListener("resize", resize);
  resize();
  draw();

  document.addEventListener("visibilitychange", () => {
    if (document.hidden) {
      cancelAnimationFrame(animationFrame);
    } else {
      draw();
    }
  });
}

