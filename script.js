function uniqueIssuers(items) {
  return ["All", ...new Set(items.map((item) => item.issuer))];
}

function renderHeroDetail() {
  if (!heroDetail || !heroHighlights) {
    return;
  }

  const detail = highlightDetails[activeHighlight];
  if (!detail) {
    return;
  }

  heroDetail.innerHTML = `
    <div class="hero-detail-header">
      <p class="hero-detail-title">${escapeHtml(detail.title)}</p>
      <a class="hero-detail-link" href="${detail.linkTarget}">${escapeHtml(detail.linkLabel)}</a>
    </div>
    <ul class="hero-detail-list">
      ${detail.items.map((item) => `<li>${escapeHtml(item)}</li>`).join("")}
    </ul>
  `;

  heroHighlights.querySelectorAll(".highlight-card").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.highlight === activeHighlight);
  });
}

